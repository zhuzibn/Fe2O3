%%Cauclation for DMI
%% next means the layer in positive z direction(i-1 in the code)
%% pre means the layer in negative z direction(i+1 in the code)
for i=1:natomH
    switch mod(i-1,3)
        case 0 %%tpye layer 1
            % pre means i+1 layer
            % nex means i-1 layer
            if i==1%layer 1 do not have the i-1 layer interaction
                mmxtmpd_nex(:,:,i)=0;
                mmytmpd_nex(:,:,i)=0;
                mmztmpd_nex(:,:,i)=0;
            else
                mmxtmpd_nex(:,:,i)=(atomtype_layer1or.*(mmx_l1(:,:,i-1) ...
                    +mmx_u1r1(:,:,i-1)+mmx_d1r1(:,:,i-1)-mmx_r2(:,:,i-1)-...
                    mmx_u1(:,:,i-1)-mmx_d1(:,:,i-1))+atomtype_layer1gr.*...
                    (mmx_r1(:,:,i-1)+mmx_u1l1(:,:,i-1)+mmx_d1l1(:,:,i-1)-mmxtmp(:,:,i-1)));

                mmytmpd_nex(:,:,i)=(atomtype_layer1or.*(mmy_l1(:,:,i-1)+ ...
                    mmy_u1r1(:,:,i-1)+mmy_d1r1(:,:,i-1)-mmy_r2(:,:,i-1)-...
                    mmy_u1(:,:,i-1)-mmy_d1(:,:,i-1))+atomtype_layer1gr.* ...
                    (mmy_r1(:,:,i-1)+mmy_u1l1(:,:,i-1)+mmy_d1l1(:,:,i-1)-mmytmp(:,:,i-1)));

                mmztmpd_nex(:,:,i)=(atomtype_layer1or.*(mmz_l1(:,:,i-1)+ ...
                    mmz_u1r1(:,:,i-1)+mmz_d1r1(:,:,i-1)-mmz_r2(:,:,i-1)-...
                    mmz_u1(:,:,i-1)-mmz_d1(:,:,i-1))+atomtype_layer1gr.* ...
                    (mmz_r1(:,:,i-1)+mmz_u1l1(:,:,i-1)+mmz_d1l1(:,:,i-1)-mmztmp(:,:,i-1)));
            end
            mmxtmpd_pre(:,:,i)=atomtype_layer1gr.*(-mmx_r1(:,:,i+1)-...
                mmx_u1l1(:,:,i+1)-mmx_d1l1(:,:,i+1)+mmx_l2(:,:,i+1)+...
                mmx_d1(:,:,i+1)+mmx_u1(:,:,i+1))-atomtype_layer1or.*...
                (mmx_l1(:,:,i+1)+mmx_d1r1(:,:,i+1)+mmx_u1r1(:,:,i+1)-mmxtmp(:,:,i+1));

            mmytmpd_pre(:,:,i)=atomtype_layer1gr.*(-mmy_r1(:,:,i+1)-...
                mmy_u1l1(:,:,i+1)-mmy_d1l1(:,:,i+1)+mmy_l2(:,:,i+1)+...
                mmy_d1(:,:,i+1)+mmy_u1(:,:,i+1))-atomtype_layer1or.* ...
                (mmy_l1(:,:,i+1)+mmy_d1r1(:,:,i+1)+mmy_u1r1(:,:,i+1)-mmytmp(:,:,i+1));

            mmztmpd_pre(:,:,i)=atomtype_layer1gr.*(-mmz_r1(:,:,i+1)-...
                mmz_u1l1(:,:,i+1)-mmz_d1l1(:,:,i+1)+mmz_l2(:,:,i+1)+...
                mmz_d1(:,:,i+1)+mmz_u1(:,:,i+1))-atomtype_layer1or.* ...
                (mmz_l1(:,:,i+1)+mmz_d1r1(:,:,i+1)+mmz_u1r1(:,:,i+1)-mmztmp(:,:,i+1));


        case 1
            mmxtmpd_pre(:,:,i)=atomtype_layer2blue.*(-mmx_r2(:,:,i+1)-...
                mmx_u1(:,:,i+1)-mmx_d1(:,:,i+1)+...
                mmx_l1(:,:,i+1)+mmx_u1r1(:,:,i+1)+...
                mmx_d1r1(:,:,i+1))-...
                atomtype_layer2p.*(mmx_l1(:,:,i+1)+...
                mmx_u1r1(:,:,i+1)+mmx_d1r1(:,:,i+1)-mmxtmp(:,:,i+1));
            mmytmpd_pre(:,:,i)=atomtype_layer2blue.*(-mmy_r2(:,:,i+1)-...
                mmy_u1(:,:,i+1)-mmy_d1(:,:,i+1)+...
                mmy_l1(:,:,i+1)+mmy_u1r1(:,:,i+1)+...
                mmy_d1r1(:,:,i+1))-...
                atomtype_layer2p.*(mmy_l1(:,:,i+1)+...
                mmy_u1r1(:,:,i+1)+mmy_d1r1(:,:,i+1)-mmytmp(:,:,i+1));
            mmztmpd_pre(:,:,i)=atomtype_layer2blue.*(-mmz_r2(:,:,i+1)-...
                mmz_u1(:,:,i+1)-mmz_d1(:,:,i+1)+...
                mmz_l1(:,:,i+1)+mmz_u1r1(:,:,i+1)+...
                mmz_d1r1(:,:,i+1))-...
                atomtype_layer2p.*(mmz_l1(:,:,i+1)+...
                mmz_u1r1(:,:,i+1)+mmz_d1r1(:,:,i+1)-mmztmp(:,:,i+1));

            mmxtmpd_nex(:,:,i)=atomtype_layer2p.*(mmx_l1(:,:,i-1)+...
                mmx_u1r1(:,:,i-1)+mmx_d1r1(:,:,i-1)-...
                mmx_r1(:,:,i-1)-mmx_u1l1(:,:,i-1)-...
                mmx_d1l1(:,:,i-1))+...
                atomtype_layer2blue.*(mmx_r2(:,:,i-1)+...
                mmx_u1(:,:,i-1)+mmx_d1(:,:,i-1)-mmxtmp(:,:,i-1));
            mmytmpd_nex(:,:,i)=atomtype_layer2p.*(mmy_l1(:,:,i-1)+...
                mmy_u1r1(:,:,i-1)+mmy_d1r1(:,:,i-1)-...
                mmy_r1(:,:,i-1)-mmy_u1l1(:,:,i-1)-...
                mmy_d1l1(:,:,i-1))+...
                atomtype_layer2blue.*(mmy_r2(:,:,i-1)+...
                mmy_u1(:,:,i-1)+mmy_d1(:,:,i-1)-mmytmp(:,:,i-1));
            mmztmpd_nex(:,:,i)=atomtype_layer2p.*(mmz_l1(:,:,i-1)+...
                mmz_u1r1(:,:,i-1)+mmz_d1r1(:,:,i-1)-...
                mmz_r1(:,:,i-1)-mmz_u1l1(:,:,i-1)-...
                mmz_d1l1(:,:,i-1))+...
                atomtype_layer2blue.*(mmz_r2(:,:,i-1)+...
                mmz_u1(:,:,i-1)+mmz_d1(:,:,i-1)-mmztmp(:,:,i-1));
        case 2%layer end do not have the i+1 layer interaction
            if i==natomH
                mmxtmpd_pre(:,:,i)=0;
                mmytmpd_pre(:,:,i)=0;
                mmztmpd_pre(:,:,i)=0;
            else
                mmxtmpd_pre(:,:,i)=(-atomtype_layer3red.*(mmx_l2(:,:,i+1)+...
                    mmx_u1(:,:,i+1)+mmx_d1(:,:,i+1)-mmxtmp(:,:,i+1))+...
                    atomtype_layer3black.*(mmx_l1(:,:,i+1)+...
                    mmx_u1r1(:,:,i+1)+mmx_d1r1(:,:,i+1)-...
                    mmx_r1(:,:,i+1)-mmx_u1l1(:,:,i+1)-...
                    mmx_d1l1(:,:,i+1)));
                mmytmpd_pre(:,:,i)=(-atomtype_layer3red.*(mmy_l2(:,:,i+1)+...
                    mmy_u1(:,:,i+1)+mmy_d1(:,:,i+1)-mmytmp(:,:,i+1))+...
                    atomtype_layer3black.*(mmy_l1(:,:,i+1)+...
                    mmy_u1r1(:,:,i+1)+mmy_d1r1(:,:,i+1)-...
                    mmy_r1(:,:,i+1)-mmy_u1l1(:,:,i+1)-...
                    mmy_d1l1(:,:,i+1)));
                mmztmpd_pre(:,:,i)=(-atomtype_layer3red.*(mmz_l2(:,:,i+1)+...
                    mmz_u1(:,:,i+1)+mmz_d1(:,:,i+1)-mmztmp(:,:,i+1))+...
                    atomtype_layer3black.*(mmz_l1(:,:,i+1)+...
                    mmz_u1r1(:,:,i+1)+mmz_d1r1(:,:,i+1)-...
                    mmz_r1(:,:,i+1)-mmz_u1l1(:,:,i+1)-...
                    mmz_d1l1(:,:,i+1)));
            end
            mmxtmpd_nex(:,:,i)=atomtype_layer3red.*(mmx_l2(:,:,i-1)+...
                mmx_u1(:,:,i-1)+mmx_d1(:,:,i-1)-...
                mmx_r1(:,:,i-1)-mmx_u1l1(:,:,i-1)-...
                mmx_d1l1(:,:,i-1))+...
                atomtype_layer3black.*(mmx_r1(:,:,i-1)+...
                mmx_u1l1(:,:,i-1)+mmx_d1l1(:,:,i-1)-mmxtmp(:,:,i-1));
            mmytmpd_nex(:,:,i)=atomtype_layer3red.*(mmy_l2(:,:,i-1)+...
                mmy_u1(:,:,i-1)+mmy_d1(:,:,i-1)-...
                mmy_r1(:,:,i-1)-mmy_u1l1(:,:,i-1)-...
                mmy_d1l1(:,:,i-1))+...
                atomtype_layer3black.*(mmy_r1(:,:,i-1)+...
                mmy_u1l1(:,:,i-1)+mmy_d1l1(:,:,i-1)-mmytmp(:,:,i-1));
            mmztmpd_nex(:,:,i)=atomtype_layer3red.*(mmz_l2(:,:,i-1)+...
                mmz_u1(:,:,i-1)+mmz_d1(:,:,i-1)-...
                mmz_r1(:,:,i-1)-mmz_u1l1(:,:,i-1)-...
                mmz_d1l1(:,:,i-1))+...
                atomtype_layer3black.*(mmz_r1(:,:,i-1)+...
                mmz_u1l1(:,:,i-1)+mmz_d1l1(:,:,i-1)-mmztmp(:,:,i-1));

        otherwise
            error('unexpected index');
    end
end

